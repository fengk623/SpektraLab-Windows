#!/usr/bin/env python3
"""The licence notice for the Rust crates linked into spk-photocraft-raw.

    python3 engine/tools/rust_crate_notices.py --cargo cargo --crate engine/raw-photocraft \
        --target x86_64-pc-windows-gnu --output Rust-crates-NOTICES.txt

Run by engine/cmake/PhotocraftRaw.cmake after the library is built. It asks
`cargo metadata --locked --offline` (the crates the lock file names, already
on disk from the build) for the dependency graph on the given target, keeps
the crates that are compiled into the static library -- normal dependencies,
followed from the root; build scripts and procedural macros run at build time
and are not distributed -- and writes one text file: an index of name,
version, licence expression and source, then every LICENSE / COPYING / NOTICE
file each crate ships.

It is also the licence gate: a crate whose SPDX expression cannot be
satisfied from the identifiers below fails the build. These are all
compatible with GPL-3.0-or-later, this repository's licence; an identifier
outside the list is a decision for a person, not something to wave through.

Standard library only.
"""
import argparse
import json
import re
import subprocess
import sys
from pathlib import Path

# GPL-3.0-or-later compatible, permissive or weak-copyleft-free. An `OR`
# expression needs one of its sides here; an `AND` expression all of them.
ALLOWED = {
    "MIT", "MIT-0", "Apache-2.0", "Apache-2.0 WITH LLVM-exception", "BSD-2-Clause", "BSD-3-Clause",
    "ISC", "Zlib", "0BSD", "Unlicense", "CC0-1.0", "Unicode-3.0", "Unicode-DFS-2016", "BSL-1.0",
}
NOTICE_FILE = re.compile(r"^(LICEN[CS]E|COPYING|COPYRIGHT|NOTICE|UNLICENSE|AUTHORS)([-_.].*)?$", re.IGNORECASE)


def satisfied(expression):
    """Whether an SPDX expression can be met from ALLOWED. Handles AND / OR / parentheses and
    the `/` some older crates write for OR."""
    text = expression.replace("/", " OR ")
    for identifier in sorted(ALLOWED, key=len, reverse=True):
        text = re.sub(r"(?<![\w.+-])" + re.escape(identifier) + r"(?![\w.+-])", " True ", text)
    text = re.sub(r"\bAND\b", " and ", text)
    text = re.sub(r"\bOR\b", " or ", text)
    # Whatever identifier is left is not allowed.
    text = re.sub(r"[A-Za-z0-9][\w.+-]*(?: WITH [\w.+-]+)?", lambda m: m.group(0) if m.group(0) in ("True", "and", "or") else " False ", text)
    if not re.fullmatch(r"[\sTrueFalsandor()]*", text):
        return False
    try:
        return bool(eval(text, {"__builtins__": {}}, {}))   # only True/False/and/or/() can reach this
    except SyntaxError:
        return False


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--cargo", default="cargo")
    parser.add_argument("--crate", required=True, help="directory of the root crate")
    parser.add_argument("--target", default="", help="Rust target triple; empty for the host")
    parser.add_argument("--output", required=True)
    args = parser.parse_args()

    command = [args.cargo, "metadata", "--locked", "--offline", "--format-version", "1"]
    if args.target:
        command += ["--filter-platform", args.target]
    metadata = json.loads(subprocess.run(command, cwd=args.crate, check=True, capture_output=True, text=True).stdout)
    packages = {p["id"]: p for p in metadata["packages"]}
    nodes = {n["id"]: n for n in metadata["resolve"]["nodes"]}
    root = metadata["resolve"]["root"]

    linked, pending = [], [root]
    seen = {root}
    while pending:
        node = nodes[pending.pop()]
        for dep in node["deps"]:
            # Normal dependencies only ("kind": null); not build or dev dependencies.
            if not any(k.get("kind") is None for k in dep.get("dep_kinds", [{"kind": None}])):
                continue
            package = packages[dep["pkg"]]
            if any("proc-macro" in t["kind"] for t in package["targets"]):
                continue   # runs in the compiler, is not in the library
            if dep["pkg"] not in seen:
                seen.add(dep["pkg"])
                linked.append(package)
                pending.append(dep["pkg"])
    linked.sort(key=lambda p: (p["name"], p["version"]))

    refused = [f'{p["name"]} {p["version"]}: {p.get("license") or "no licence expression"}'
               for p in linked if not p.get("license") or not satisfied(p["license"])]
    if refused:
        sys.exit("Rust crates whose licence is not on the allowed list (engine/tools/rust_crate_notices.py):\n  "
                 + "\n  ".join(refused))

    out = [
        "Rust crates statically linked into this binary through spk-photocraft-raw",
        "(engine/raw-photocraft; exact versions: its Cargo.lock). Generated by",
        "engine/tools/rust_crate_notices.py from `cargo metadata`" + (f" for {args.target}." if args.target else "."),
        "",
        f"{'crate':28} {'version':12} licence",
    ]
    for p in linked:
        out.append(f"{p['name']:28} {p['version']:12} {p['license']}")
    out += ["", "The Rust standard library (MIT OR Apache-2.0) is linked as well; its licence texts are",
            "the same MIT and Apache-2.0 texts reproduced below.", ""]
    def notice_files(package):
        directory = Path(package["manifest_path"]).parent
        return sorted(f for f in directory.iterdir() if f.is_file() and NOTICE_FILE.match(f.name))

    missing = []
    for p in linked:
        notices = notice_files(p)
        out += ["=" * 78, f"{p['name']} {p['version']}  ({p['license']})",
                p.get("repository") or p.get("homepage") or "", "=" * 78, ""]
        if not notices:
            # Some crates are published without their repository's licence
            # file. Another linked crate from the same repository carries it.
            sibling = next((q for q in linked if q is not p and q.get("repository")
                            and q.get("repository") == p.get("repository") and notice_files(q)), None)
            if sibling:
                notices = notice_files(sibling)
                out += [f"(this crate's package ships no licence file; the files below are from "
                        f"{sibling['name']} {sibling['version']}, published from the same repository)", ""]
            else:
                missing.append(f"{p['name']} {p['version']}")
                out += ["(this crate's package ships no licence file; its licence expression is above)", ""]
        for notice in notices:
            out += [f"--- {notice.name} ---", notice.read_text(encoding="utf-8", errors="replace").rstrip(), ""]
    Path(args.output).write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"{len(linked)} linked Rust crates, all on the allowed licence list; notices in {args.output}")
    if missing:
        print("crates that ship no licence file: " + ", ".join(missing))


if __name__ == "__main__":
    main()
